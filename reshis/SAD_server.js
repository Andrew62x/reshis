function parseCsv(text) {
  const lines = text.trim().split('\n');
  const header = lines[0].split(',');
  const rows = [];
  for (let i = 1; i < lines.length; i++) {
    const vals = lines[i].split(',');
    const row = {};
    for (let j = 0; j < header.length; j++) row[header[j]] = vals[j];
    rows.push(row);
  }
  return rows;
}

