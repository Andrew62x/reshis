// желают = X_base_demand − price_sensitivity × (цена − base_price)
function demandAt(baseDemand, sensitivity, basePrice, price) {
  return baseDemand - sensitivity * (price - basePrice);
}

// купят = min(seats, max(0, желают))
function salesAt(baseDemand, sensitivity, basePrice, price, seats) {
  return Math.min(seats, Math.max(0, demandAt(baseDemand, sensitivity, basePrice, price)));
}

function buildForecast(route, date, price) {
  const info = ROUTES[route];
  const rec = FORECAST[route + '|' + date];
  if (!info) return { error: 'Неизвестный маршрут' };
  if (!rec) return { error: 'Для этого маршрута и даты нет прогноза' };
  if (!isFinite(price) || price <= 0) return { error: 'Цена должна быть положительным числом' };

  const ps = info.price_sensitivity;
  const bp = info.base_price;
  const seats = rec.seats;

  // Простой прогноз: медианный сценарий (0.5)
  const median = rec.quantiles['0.5'];
  const want = demandAt(median.baseDemand, ps, bp, price);
  const sales = Math.min(seats, Math.max(0, want));

  // Распределение спроса: спрос при введённой цене для каждого квантиля
  const quantiles = QUANTILES.map(function (t) {
    const q = rec.quantiles[t];
    const d = demandAt(q.baseDemand, ps, bp, price);
    const s = Math.min(seats, Math.max(0, d));
    return {
      q: +t,
      baseDemand: q.baseDemand,
      demand: Math.round(d * 10) / 10,
      sales: Math.round(s),
      optPrice: q.optPrice,
      optSales: q.optSales
    };
  });

  return {
    route: route,
    name: info.name,
    date: date,
    seats: seats,
    base_price: bp,
    price_min: info.price_min,
    price_max: info.price_max,
    cost_per_passenger: info.cost_per_passenger,
    price: price,
    sensitivity: ps,
    medianDemand: Math.round(want * 10) / 10,
    sales: Math.round(sales),
    revenue: Math.round(price * sales),
    profit: Math.round((price - info.cost_per_passenger) * sales),
    optimalPrice: median.optPrice,
    optimalSales: median.optSales,
    optimalProfit: Math.round((median.optPrice - info.cost_per_passenger) * median.optSales),
    quantiles: quantiles
  };
}

